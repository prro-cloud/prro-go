// Package prro — Go-клієнт для машинного API сервісу PRRO.cloud: реєстрація
// чеків програмного РРО, керування змінами, білінг і вебхуки.
//
// Бібліотека не має залежностей поза стандартною бібліотекою Go.
//
// # Початок роботи
//
// Токен випускають у кабінеті PRRO.cloud у розділі токенів. Клієнт безпечний
// для одночасного використання з кількох горутин — створюйте один на
// застосунок:
//
//	c := prro.NewClient(os.Getenv("PRRO_TOKEN"))
//	me, err := c.System.WhoAmI(ctx)
//
// # Ідемпотентність
//
// Кожна фіскальна операція несе заголовок Idempotency-Key: повтор запиту з
// тим самим ключем повертає початкове завдання, а не реєструє другий
// документ. Якщо ключ не передано через [WithIdempotencyKey], клієнт
// генерує його сам (UUIDv7) — цього досить для безпечних повторів у межах
// одного виклику. Щоб повтор був безпечним і після перезапуску застосунку,
// передавайте власний ключ, похідний від замовлення, — наприклад
// "order-10412".
//
// # Повтори
//
// Мережеві збої та відповіді 429, 500, 502, 503 і 504 клієнт повторює з
// експоненційною затримкою, але лише для запитів, які безпечно повторити:
// GET, PUT і фіскальних операцій з Idempotency-Key. Кількість повторів
// задає [WithRetry].
//
// # Помилки
//
// Відповідь API з помилкою повертається як [*Error]: HTTP-статус, машинний
// код і текст для людини. Типові випадки перевіряють через [errors.Is]:
//
//	_, err := c.System.WhoAmI(ctx)
//	switch {
//	case errors.Is(err, prro.ErrUnauthorized):
//		// токен недійсний або відкликаний
//	case errors.Is(err, prro.ErrPaymentRequired):
//		// баланс вичерпано — нові чеки заблоковано до поповнення
//	}
//
// Фіскальне завдання, що завершилося помилкою, дає [ErrTaskFailed]; його
// структурований опис — у полі [Error.Fault].
